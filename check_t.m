function t_out = check_t(t)
% ============================================================
% 处理"时间差跨过 GPS 周界"的问题
% 一周 = 604800 秒。时间差超过半周(302400)说明算错了周，
% 要往回/往前修正一周。
% ============================================================
t_out = t;
if (t > 302400)
    t_out = t - 604800;
end
if (t < -302400)
    t_out = t + 604800;
end
end
