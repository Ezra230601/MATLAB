function time = weektow2time(week, tow, system)
% ============================================================
% 把"GPS 周数 + 周内秒"换算成"连续秒数"（从 1980-01-06 0 点起算）
% 用法： time = weektow2time(week, tow, 'G')
% 说明：本项目其他代码统一用"连续秒数"记录时间，
%       这样两个时刻相减就是相差多少秒，不用再算周数。
% ============================================================

time = week * 7 * 86400 + tow;

% 北斗时间(BDT)比 GPS 时间慢 14 秒，这里补上
if nargin > 2 && strcmp(system, 'C')
    time = time + 14;
end

end
