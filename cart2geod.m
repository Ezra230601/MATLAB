function [phi, lam, h] = cart2geod(X, Y, Z)
% ============================================================
% 地固系直角坐标 (X,Y,Z) -> 大地坐标 (经纬度、海拔)
% 输出：phi 纬度(弧度), lam 经度(弧度), h 海拔(米)
% WGS84 椭球
% ============================================================
a  = 6378137.0;               % 长半轴
f  = 1/298.257223563;         % 扁率
e2 = f*(2-f);                 % 偏心率平方

lam = atan2(Y, X);            % 经度一步到位
p   = sqrt(X^2 + Y^2);
phi = atan2(Z, p*(1-e2));     % 纬度给初值后迭代
h   = 0;
for k = 1:10
    N   = a / sqrt(1 - e2*sin(phi)^2);
    h   = p/cos(phi) - N;
    phi = atan2(Z, p*(1 - e2*N/(N+h)));
end
end
