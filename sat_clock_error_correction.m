function dtS = sat_clock_error_correction(time, Eph)
% ============================================================
% 计算卫星钟差：dt = af0 + af1*(t-toc) + af2*(t-toc)^2
% 输入：time = 信号发射时刻(GPS连续秒)；Eph = 一组星历
% 注意：Eph(33) 才是连续秒的钟差参考时刻，Eph(21) 是周内秒
% ============================================================
af0 = Eph(19);    % 钟差常数项
af1 = Eph(20);    % 钟差一阶项
af2 = Eph(2);     % 钟差二阶项
toc = Eph(33);    % 钟差参考时刻(连续GPS秒) —— 这里原来是 Eph(21)，那是周内秒
dtS = af0 + af1*(time - toc) + af2*(time - toc)^2;
end
